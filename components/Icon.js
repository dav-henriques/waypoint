const SIZE_DEFAULT = 22;

export function icon(name, { size = SIZE_DEFAULT, stroke = 1.6, cls = "", solid = false } = {}) {
  const def = ICONS[name] || ICONS.pin;
  const shapes = Array.isArray(def) ? def : [def];
  const kids = shapes.map((s) => {
    if (s.t === "circle") {
      return h("circle", {
        cx: s.cx, cy: s.cy, r: s.r,
        ...(s.solid ? { fill: "currentColor", stroke: "none" } : {}),
      });
    }
    return h("path", { d: s.d });
  });
  return h("svg", {
    class: cls,
    width: size,
    height: size,
    viewBox: "0 0 24 24",
    "stroke-width": stroke,
    "aria-hidden": "true",
    ...(solid ? { fill: "currentColor", stroke: "currentColor", "stroke-width": stroke } : {}),
  }, kids);
}

